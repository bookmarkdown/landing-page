export function translate(locale, key, parameters = {}) {
  const message = messages[locale]?.[key] ?? messages.en[key];
  if (message === undefined) throw new Error(`Unknown translation key: ${key}`);
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => String(parameters[name] ?? placeholder));
}