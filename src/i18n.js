export const supportedLocales = ['en', 'zh-Hant', 'zh-Hans'];

export function matchLocale(language) {
  if (typeof language !== 'string') return null;
  const parts = language.toLowerCase().replaceAll('_', '-').split('-');
  if (parts[0] === 'en') return 'en';
  if (parts[0] !== 'zh') return null;
  if (parts.includes('hant')) return 'zh-Hant';
  if (parts.includes('hans')) return 'zh-Hans';
  return parts.some(part => ['tw', 'hk', 'mo'].includes(part)) ? 'zh-Hant' : 'zh-Hans';
}

export function resolveLocale({ requested, saved, languages = [] } = {}) {
  for (const language of [requested, requested === 'auto' ? null : saved, ...languages]) {
    const locale = matchLocale(language);
    if (locale) return locale;
  }
  return 'en';
}

